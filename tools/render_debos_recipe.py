#!/usr/bin/env python3
"""
Render build/debos/aura.yaml from the shared package lists so the debos
disk image always matches the ISO and the installer. Re-run after editing
build/packages/*.txt.  Usage: python3 tools/render_debos_recipe.py
"""
import os

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
OUT = os.path.join(ROOT, "build", "debos", "aura.yaml")


def read_list(name):
    pkgs = []
    with open(os.path.join(ROOT, "build", "packages", name),
              encoding="utf-8") as fh:
        for line in fh:
            line = line.strip()
            if line and not line.startswith("#"):
                pkgs.append(line)
    return pkgs


TEMPLATE = """# AURA OS debos recipe — preinstalled ARM64 disk image for UTM.
# GENERATED by tools/render_debos_recipe.py from build/packages/*.txt.
# Build with:  ./build/build-image.sh        (ARM64 Debian/Ubuntu host)

architecture: arm64

actions:
  # Partition first so every later step writes straight into the image.
  - action: image-partition
    description: Create GPT disk (EFI + root)
    imagename: AURA-OS-1.0-arm64.img
    imagesize: 12GB
    partitiontype: GPT
    mountpoints:
      - mountpoint: /
        partition: root
        options: [x-systemd.growfs]
      - mountpoint: /boot/efi
        partition: esp
    partitions:
      - name: esp
        fs: fat32
        start: 0%
        end: 256MB
        label: efi
        flags: [esp]
      - name: root
        fs: ext4
        start: 256MB
        end: 100%
        label: rootfs

  - action: debootstrap
    description: Bootstrap Debian bookworm (arm64)
    suite: bookworm
    components: [main, contrib, non-free-firmware]
    mirror: https://deb.debian.org/debian
    variant: minbase

  - action: apt
    description: Install AURA OS packages (core + boot)
    recommends: false
    packages:
@@PACKAGES@@

  - action: overlay
    description: AURA OS overlay (themes, apps, Celestia, branding)
    source: ../../rootfs
    destination: /

  - action: run
    description: Install GRUB for UEFI (removable media path — UTM-safe)
    chroot: true
    command: |
      set -e
      echo aura-os > /etc/hostname
      grub-install --target=arm64-efi --efi-directory=/boot/efi \\
                   --bootloader-id=AURA --removable --no-nvram
      mkdir -p /etc/default/grub.d
      update-grub

  - action: run
    description: Create the default user and finalize AURA
    chroot: true
    command: |
      set -e
      useradd -m -s /bin/zsh -c "AURA User" \\
              -G sudo,audio,video,plugdev,netdev,input,cdrom aura
      echo "aura:aura" | chpasswd
      chage -d 0 aura   # force a password change at first login
      /usr/share/aura/finalize.sh --user aura
      apt-get clean

  - action: run
    description: Tidy the image
    chroot: true
    command: |
      rm -rf /var/log/* /tmp/* /var/tmp/* 2>/dev/null || true
      truncate -s 0 /etc/machine-id || true
      rm -f /var/lib/dbus/machine-id || true
"""


def main():
    pkgs = read_list("core.txt") + read_list("image.txt")
    lines = "\n".join(f"      - {p}" for p in pkgs)
    recipe = TEMPLATE.replace("@@PACKAGES@@", lines)
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write(recipe)
    print(f"Wrote {OUT} with {len(pkgs)} packages.")


if __name__ == "__main__":
    main()
