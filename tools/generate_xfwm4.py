#!/usr/bin/env python3
"""
Generate xfwm4 window decorations (XPM) for AuraDark / AuraLight.

Rounded top corners, a subtle vertical titlebar gradient, and AURA's signature
blue-glass circle buttons (× / – / +). Run: python3 tools/generate_xfwm4.py
"""
import math
import os

BASE = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..",
                    "rootfs", "usr", "share", "themes")

CHARS = "abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789@#%$&*+-=;:<>~^/()[]{}?|_!$'"


def to_xpm(pixels, w, h):
    """pixels: list of rows of (r,g,b) or None for transparent."""
    colors = {}
    lines = []
    for row in pixels:
        s = ""
        for px in row:
            if px is None:
                s += " "
            else:
                if px not in colors:
                    colors[px] = CHARS[len(colors)]
                s += colors[px]
        lines.append(s)
    out = ["/* XPM */", "static char * xpm[] = {"]
    out.append(f'"{w} {h} {len(colors) + 1} 1",')
    out.append('"  c None",')
    for (r, g, b), ch in sorted(colors.items(), key=lambda kv: kv[1]):
        out.append(f'"{ch} c #{r:02x}{g:02x}{b:02x}",')
    for i, s in enumerate(lines):
        out.append(f'"{s}"' + ("," if i < len(lines) - 1 else "};"))
    return "\n".join(out) + "\n"


def lerp(c1, c2, t):
    return tuple(int(round(a + (b - a) * t)) for a, b in zip(c1, c2))


def gradient(w, h, top, bottom):
    return [[lerp(top, bottom, y / max(h - 1, 1)) for _ in range(w)]
            for y in range(h)]


def rounded_top(pixels, w, h, radius, left=True):
    for y in range(min(radius, h)):
        for x in range(min(radius, w)):
            cx = radius - 1 - (x if left else 0)
            dx = (radius - 1 - x) if left else (x - (w - radius))
            dy = radius - 1 - y
            if (dx * dx + dy * dy) > radius * radius:
                col = x if left else x
                pixels[y][col] = None
    return pixels


def draw_button(w, h, bg_top, bg_bottom, circle_color, glyph, glyph_color):
    px = gradient(w, h, bg_top, bg_bottom)
    cx, cy, r = w / 2 - 0.5, h / 2 - 0.5, 7.0
    for y in range(h):
        for x in range(w):
            d = math.hypot(x - cx, y - cy)
            if d <= r:
                px[y][x] = lerp(circle_color, (255, 255, 255),
                                max(0.0, 1 - (y - (cy - r)) / (2 * r)) * 0.18)
    def plot(x, y):
        for dy in (-0.6, 0, 0.6):
            for dx in (-0.6, 0, 0.6):
                xi, yi = int(round(x + dx)), int(round(y + dy))
                if 0 <= xi < w and 0 <= yi < h:
                    px[yi][xi] = glyph_color
    steps = 9
    if glyph == "x":
        for i in range(-steps, steps + 1):
            plot(cx + i * 0.35, cy + i * 0.35)
            plot(cx + i * 0.35, cy - i * 0.35)
    elif glyph == "-":
        for i in range(-steps, steps + 1):
            plot(cx + i * 0.35, cy)
    elif glyph == "+":
        for i in range(-steps, steps + 1):
            plot(cx + i * 0.35, cy)
            plot(cx, cy + i * 0.35)
    elif glyph == "v":  # menu / shade chevron
        for i in range(steps + 1):
            plot(cx - 3 + i * 0.35, cy - 1.5 + i * 0.3)
            plot(cx + 3 - i * 0.35, cy - 1.5 + i * 0.3)
    elif glyph == "^":
        for i in range(steps + 1):
            plot(cx - 3 + i * 0.35, cy + 1.5 - i * 0.3)
            plot(cx + 3 - i * 0.35, cy + 1.5 - i * 0.3)
    else:  # dot
        plot(cx, cy)
    return px


THEMES = {
    "AuraDark": dict(
        active_top=(27, 49, 87), active_bottom=(16, 28, 51),
        inactive_top=(22, 38, 63), inactive_bottom=(13, 22, 40),
        frame=(16, 28, 51), frame_inactive=(13, 22, 40),
        btn=(47, 127, 224), btn_close=(227, 93, 106),
        btn_pressed=(29, 95, 192), btn_inactive=(90, 113, 148),
        glyph=(255, 255, 255),
        themerc_text=("#e8f1fc", "#9db4d0"),
    ),
    "AuraLight": dict(
        active_top=(255, 255, 255), active_bottom=(226, 238, 251),
        inactive_top=(240, 247, 255), inactive_bottom=(217, 231, 246),
        frame=(200, 219, 240), frame_inactive=(205, 222, 240),
        btn=(47, 127, 224), btn_close=(227, 93, 106),
        btn_pressed=(29, 95, 192), btn_inactive=(160, 182, 208),
        glyph=(255, 255, 255),
        themerc_text=("#12233d", "#5a7194"),
    ),
}

THEMERC = """# AURA OS xfwm4 theme — generated by tools/generate_xfwm4.py
active_text_color={active}
inactive_text_color={inactive}
active_text_shadow_color=#00000022
inactive_text_shadow_color=#00000011
button_offset=6
button_spacing=2
full_width_title=true
title_horizontal_offset=2
title_vertical_offset_active=2
title_vertical_offset_inactive=2
title_shadow_active=false
title_shadow_inactive=false
shadow_delta_height=2
shadow_delta_width=0
shadow_delta_x=0
shadow_delta_y=-10
shadow_opacity=55
resize_opacity=100
move_opacity=90
placement_ratio=20
"""

TITLE_H = 28


def build_theme(name, t):
    d = os.path.join(BASE, name, "xfwm4")
    os.makedirs(d, exist_ok=True)

    def save(fname, pixels, w, h):
        with open(os.path.join(d, fname), "w", encoding="ascii") as fh:
            fh.write(to_xpm(pixels, w, h))

    for state in ("active", "inactive"):
        top, bot = t[f"{state}_top"], t[f"{state}_bottom"]
        frame = t["frame"] if state == "active" else t["frame_inactive"]
        # title pieces 1..5 (2/4 are text side spacers — same gradient)
        for i in range(1, 6):
            save(f"title-{i}-{state}.xpm", gradient(8, TITLE_H, top, bot), 8, TITLE_H)
        # rounded corners
        tl = rounded_top(gradient(12, TITLE_H, top, bot), 12, TITLE_H, 10, left=True)
        tr = rounded_top(gradient(12, TITLE_H, top, bot), 12, TITLE_H, 10, left=False)
        save(f"top-left-{state}.xpm", tl, 12, TITLE_H)
        save(f"top-right-{state}.xpm", tr, 12, TITLE_H)
        save(f"left-{state}.xpm", [[frame] * 4 for _ in range(8)], 4, 8)
        save(f"right-{state}.xpm", [[frame] * 4 for _ in range(8)], 4, 8)
        save(f"bottom-{state}.xpm", [[frame] * 8 for _ in range(6)], 8, 6)
        save(f"bottom-left-{state}.xpm", [[frame] * 4 for _ in range(6)], 4, 6)
        save(f"bottom-right-{state}.xpm", [[frame] * 4 for _ in range(6)], 4, 6)
        # buttons
        glyphs = {"close": "x", "hide": "-", "maximize": "+", "menu": "v",
                  "shade": "^", "stick": "."}
        for btn, gl in glyphs.items():
            color = t["btn_close"] if (btn == "close" and state == "active") else \
                    t["btn"] if state == "active" else t["btn_inactive"]
            px = draw_button(22, TITLE_H, top, bot, color,
                             gl if state == "active" else "", t["glyph"])
            save(f"{btn}-{state}.xpm", px, 22, TITLE_H)
            if state == "active":
                pxp = draw_button(22, TITLE_H, top, bot, t["btn_pressed"], gl, t["glyph"])
                save(f"{btn}-pressed.xpm", pxp, 22, TITLE_H)
                save(f"{btn}-toggled-active.xpm", pxp, 22, TITLE_H)
    with open(os.path.join(d, "themerc"), "w", encoding="utf-8") as fh:
        fh.write(THEMERC.format(active=t["themerc_text"][0],
                                 inactive=t["themerc_text"][1]))
    print("xfwm4:", name)


if __name__ == "__main__":
    for n, t in THEMES.items():
        build_theme(n, t)
    print("xfwm4 themes generated.")
