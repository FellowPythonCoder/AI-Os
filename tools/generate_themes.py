def main():
    for theme, pal in PALETTES.items():
        for sub, tpl in (("gtk-3.0", GTK3), ("gtk-4.0", GTK4)):
            d = os.path.join(BASE, theme, sub)
            os.makedirs(d, exist_ok=True)
            with open(os.path.join(d, "gtk.css"), "w", encoding="utf-8") as fh:
                fh.write(tpl.substitute(pal))
            with open(os.path.join(d, "accent.css"), "w", encoding="utf-8") as fh:
                fh.write(ACCENT_CSS)
            with open(os.path.join(d, "glass.css"), "w", encoding="utf-8") as fh:
                fh.write(pal["GLASS_CSS"])
            with open(os.path.join(d, "font.css"), "w", encoding="utf-8") as fh:
                fh.write(FONT_CSS)
            print("theme:", theme, sub)
        dark = os.path.join(BASE, theme, "gtk-3.0", "gtk-dark.css")
        with open(dark, "w", encoding="utf-8") as fh:
            fh.write('@import url("gtk.css");\n')
    print("AURA Liquid Glass themes generated.")


if __name__ == "__main__":
    main()
